import 'dotenv/config';
import fs from 'node:fs';
import path from 'node:path';
import solc from 'solc';
import {Wallet,JsonRpcProvider,ContractFactory} from 'ethers';
const rpc=process.env.HADRIAN_RPC||'https://hadrian.testnet.romeprotocol.xyz/';
if(!process.env.ANCHOR_PRIVATE_KEY) throw Error('Set ANCHOR_PRIVATE_KEY in .env (a fresh test-only wallet; never commit it)');
const source=fs.readFileSync(path.resolve('contracts/RomeIDRegistry.sol'),'utf8');
const input={language:'Solidity',sources:{'RomeIDRegistry.sol':{content:source}},settings:{outputSelection:{'*':{'*':['abi','evm.bytecode.object']}}}};
const output=JSON.parse(solc.compile(JSON.stringify(input)));
for(const err of output.errors||[]) console.log(err.formattedMessage);
if(output.errors?.some(x=>x.severity==='error'))throw Error('Solidity compilation failed');
const c=output.contracts['RomeIDRegistry.sol'].RomeIDRegistry;
const provider=new JsonRpcProvider(rpc,200010);
const wallet=new Wallet(process.env.ANCHOR_PRIVATE_KEY,provider);
console.log('Deploying from',wallet.address,'balance',String(await provider.getBalance(wallet.address)));
const factory=new ContractFactory(c.abi,'0x'+c.evm.bytecode.object,wallet);
const contract=await factory.deploy(wallet.address);
console.log('Deployment tx:',contract.deploymentTransaction().hash);
await contract.waitForDeployment();
console.log('REGISTRY ADDRESS:',await contract.getAddress());
console.log('Add ANCHOR_CONTRACT_ADDRESS to .env, then restart backend.');
